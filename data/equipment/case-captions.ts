export function withNonSmallCaseCaptions<T extends EquipmentCategoryPageData>(data: T): T {
  return {
    ...data,
    cases: data.cases.map((equipmentCase) => {
      const captions = CASE_CAPTIONS[equipmentCase.id]
      if (!captions) return equipmentCase

      return {
        ...equipmentCase,
        images: equipmentCase.images.map((image, imageIndex) => ({
          ...image,
          caption: `${equipmentCase.name}／${equipmentCase.location}｜${
            captions[imageIndex] ?? captions.at(-1)
          }`,
        })),
      }
    }),
  }
}
